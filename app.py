# 确定查询对象
target_name = ""
target_id = ""

if keyword.strip():
    kw = keyword.strip()
    hit = students[(students["姓名"].str.contains(kw, na=False)) | (students["学号"].str.contains(kw, na=False))]
    if len(hit) == 0:
        st.warning(f"未找到「{kw}」的记录，请检查姓名或学号。")
        st.stop()
    if len(hit) > 1:
        st.info(f"找到 {len(hit)} 条匹配，请从左侧下拉框精确选择。")
        st.dataframe(hit, use_container_width=True, hide_index=True)
        st.stop()
    target_name = hit.iloc[0]["姓名"]
    target_id = hit.iloc[0]["学号"]
elif selected:
    m = re.match(r"(.+?)（(.+?)）", selected)
    if m:
        target_name, target_id = m.group(1), m.group(2)
else:
    st.info("👈 请在左侧输入姓名或学号，或从下拉框选择。")
    st.stop()

# ---------- 该生的所有记录 ----------
if target_id:
    person = df_all[df_all["学号"] == target_id].copy()
else:
    person = df_all[df_all["姓名"] == target_name].copy()

if person.empty:
    st.warning(f"「{target_name}」暂无记录。")
    st.stop()

# ---------- 顶部信息 ----------
st.subheader(f"👤 {target_name}　学号：{target_id or '—'}")

# ---------- 统计卡片 ----------
duty_score = person[person["类别"]=="履职尽责"]["加分"].max() if not person[person["类别"]=="履职尽责"].empty else 0
human_score = person[person["类别"]=="人文修养"]["加分"].sum()
total = duty_score + human_score

c1, c2, c3 = st.columns(3)
c1.metric("履职尽责（取最高）", f"{duty_score:.1f} 分")
c2.metric("人文修养（累计）", f"{human_score:.1f} 分")
c3.metric("合计加分", f"{total:.1f} 分")

# ---------- 明细表 ----------
