df_51 = pd.DataFrame(DATA_51, columns=["姓名","学号","学院","评价等级","部门"])
df_52 = pd.DataFrame(DATA_52, columns=["姓名","学号","职务","加分"])
df_53 = pd.DataFrame(DATA_53, columns=["姓名","学号","职务","加分"])
df_42 = pd.DataFrame(DATA_42, columns=["学号","姓名","学院","活动名称","时长"])

# 履职尽责加分规则：A=5, B=4, C=3
grade_score = {"A": 5, "B": 4, "C": 3}
df_51["加分"] = df_51["评价等级"].map(grade_score).fillna(0)

# 合并履职数据（5.1 + 5.2 + 5.3），取最高分
df_duty = pd.concat([
    df_51[["姓名","学号","部门","加分"]].rename(columns={"部门":"来源"}),
    df_52[["姓名","学号","职务","加分"]].rename(columns={"职务":"来源"}),
    df_53[["姓名","学号","职务","加分"]].rename(columns={"职务":"来源"}),
], ignore_index=True)
df_duty["类别"] = "履职尽责"

# 人文修养（4.2），按时长累计
df_human = df_42.rename(columns={"活动名称":"来源","时长":"加分"}).copy()
df_human["类别"] = "人文修养"

# 所有记录合并
df_all = pd.concat([
    df_duty[["姓名","学号","类别","来源","加分"]],
    df_human[["姓名","学号","类别","来源","加分"]],
], ignore_index=True)

# 学生总表（去重）
students = df_all[["姓名","学号"]].drop_duplicates().sort_values("学号").reset_index(drop=True)

